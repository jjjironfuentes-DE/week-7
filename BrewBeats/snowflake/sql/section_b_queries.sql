-- B.1 Top 5 coffee types by revenue

SELECT
    COFFEE_NAME,
    ROUND(SUM(MONEY), 2) AS TOTAL_REVENUE
FROM COFFEE_SALES
GROUP BY COFFEE_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;

-- Q2 Total revenue by payment type

SELECT
    CASH_TYPE,
    ROUND(SUM(MONEY), 2) AS TOTAL_REVENUE
FROM COFFEE_SALES
GROUP BY CASH_TYPE
ORDER BY TOTAL_REVENUE DESC;

-- Q3 Total revenue per month using a CTE

WITH MONTHLY_REVENUE AS (
    SELECT
        DATE_TRUNC('MONTH', DATE) AS SALES_MONTH,
        SUM(MONEY) AS TOTAL_REVENUE
    FROM COFFEE_SALES
    GROUP BY DATE_TRUNC('MONTH', DATE)
)

SELECT
    SALES_MONTH,
    ROUND(TOTAL_REVENUE, 2) AS TOTAL_REVENUE
FROM MONTHLY_REVENUE
ORDER BY SALES_MONTH;

-- Q4 Find the day with the highest number of transactions

SELECT
    DATE,
    COUNT(*) AS TOTAL_TRANSACTIONS
FROM COFFEE_SALES
GROUP BY DATE
ORDER BY TOTAL_TRANSACTIONS DESC
LIMIT 1;